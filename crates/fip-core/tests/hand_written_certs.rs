//! Pins the hand-written strict certificates of this crate (none; the crate root
//! re-exports two generated ones). Adding one requires updating this list and
//! justifying it.

#[test]
fn hand_written_certificates_are_exactly_the_documented_ones() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let found: Vec<(String, String)> = fip_testkit::certs::hand_written(&dir)
        .into_iter()
        .map(|(f, _, line)| {
            let file = f
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            let ident = line
                .split(|c: char| !(c.is_alphanumeric() || c == '_'))
                .find(|w| w.starts_with("__fip_strict_"))
                .unwrap_or("")
                .to_string();
            (file, ident)
        })
        .collect();
    // None made by hand since phase 5 (decision 2026-11-06-redesign-verus-allocates):
    // the certificates are generated by `#[fip_macros::fip(strict ..)]`/`(total)`;
    // `lib.rs` only re-exports the two of the public functions at the crate root
    // (the scan lists every `__fip_strict_` identifier in source).
    let mut found = found;
    found.sort();
    assert_eq!(
        found,
        vec![
            ("lib.rs".to_string(), "__fip_strict_replace".to_string()),
            ("lib.rs".to_string(), "__fip_strict_swap".to_string()),
        ]
    );
}

/// The generated certificates name their functions, so aliasing one for another
/// function fails.
#[test]
fn generated_certificates_carry_their_names() {
    assert_eq!(fip_core::__fip_strict_swap.allocs_for("swap"), 0);
    assert_eq!(fip_core::__fip_strict_replace.name(), "replace");
    assert!(fip_core::__fip_strict_replace.no_panic_macros_for("replace"));
    let r = std::panic::catch_unwind(|| fip_core::__fip_strict_swap.allocs_for("replace"));
    assert!(
        r.is_err(),
        "a certificate must not be accepted for another name"
    );
}
