//! # fip-core — allocation-free, in-place building blocks
//!
//! Building blocks for code written in the style of *FP²: Fully in-Place
//! Functional Programming* (Lorenzen, Leijen, Swierstra, ICFP 2023).
//!
//! ## What this crate guarantees, and how
//!
//! - **No heap allocation, by construction.** The crate is `#![no_std]`, does not
//!   link `alloc`, and depends only on workspace crates without `alloc` (`fip-strict`,
//!   and the proc-macro `fip-macros`, which runs on the host). There is no allocator
//!   API it could call.
//!   This is a crate-boundary guarantee, not a lint.
//! - **No `unsafe`** (`#![forbid(unsafe_code)]`). The strict certificates of `swap`
//!   and `replace` are made in `fip-strict` (`fip_strict::certs`) and re-exported
//!   here, in plain builds only; Verus never sees them.
//! - **Strict variants** ([`strict`]): `compact`, `dedup_by`, `compact_map`,
//!   `map_in_place`, `update`, `map_in_place_st` and `compact_map_st` taking
//!   `fip_strict::FipFn` callables, with
//!   certificates generated by `#[fip(strict = true, param(..))]` (plain builds), and
//!   verified against `FipFn::pre` / `FipFn::post` (Verus imports `fip-strict`'s
//!   Verus build: `just verify-strict verify-core`). Dependencies: `fip-strict` and
//!   the proc-macro `fip-macros`, both in this workspace.
//! - **Functional correctness, by proof.** Every public function carries a Verus
//!   specification (`#[cfg_attr(verus_keep_ghost, verus_spec(..))]`) and is verified
//!   with `verus --no-cheating`. A plain `cargo` build never sees the specifications:
//!   the `verus_keep_ghost` cfg is set only by the `verus` driver, so the crate has
//!   no build-time dependency on Verus or `vstd`.
//!
//! - **Bounded stack, by acyclic call graph.** Verus rejects any recursion among
//!   verified functions that lacks a `decreases` clause; no function here has one
//!   (checked by `tests/verified_surface.rs`, and a recursive mutant is rejected by
//!   `just verify-negative`). With no recursion and fixed-size frames, stack depth is
//!   bounded by the longest call chain. Every loop has a proved `decreases` measure.
//!
//! ## What it does not guarantee
//!
//! - Closures passed in (`keep`, `same`, `f`) are the caller's code; this crate makes
//!   no claim about what they allocate or how much stack they use. The strict
//!   variants require certified callables with bound 0, checked when the
//!   instantiation is built.
//! - The stack bound is structural (no recursion), not a byte count.
//!
//! ## State-passing variants
//!
//! `map_in_place_st` and `compact_map_st` thread an explicit state through the
//! callable (`Fn(S, T) -> (S, ..)`) instead of letting an `FnMut` closure mutate a
//! captured one. Verus does not model what a `FnMut` call does to the closure's
//! captured state (after the call it proves the closure unchanged) and rejects
//! closures capturing a local mutably, so an `FnMut` variant's proof would say nothing
//! about the state. Passed by value, every intermediate state is named in the
//! postcondition (`spec::state`): the trace is a spec function of the call
//! (`map_st_by_trace`, `compact_map_st_by_witnesses`), and `f` need only accept the
//! states a caller-chosen invariant `inv(k, s)` allows before call `k`
//! (`map_st_by_inv`), which then holds along the trace.
//!
//! ## Panics
//!
//! Apart from `swap` with an out-of-bounds index (excluded by its verified
//! precondition), no function here panics by itself. If a callable panics, the slot or
//! slice holds only valid values, none moved-from or dropped twice: the `# Panics`
//! section of each function says which (measured in `tests/panic_state.rs`).
//!
//! ## Placeholders
//!
//! Functions that move a value out of a `&mut` slot need something to leave behind.
//! This crate never manufactures one (no `Default` bound, no `mem::take`): the caller
//! passes a `hole` value and gets it back. A capability-like type therefore never has
//! to be minted just to satisfy a placeholder.

#![no_std]
#![cfg_attr(fip_prelint, fip::export)]
#![forbid(unsafe_code)]
#![cfg_attr(verus_keep_ghost, feature(proc_macro_hygiene))]

// Plain builds: proof-only blocks expand to nothing. Under `verus` the real macros
// come from `vstd::prelude`.
#[cfg(not(verus_keep_ghost))]
macro_rules! proof {
    ($($t:tt)*) => {};
}
#[cfg(not(verus_keep_ghost))]
macro_rules! proof_decl {
    ($($t:tt)*) => {};
}

pub mod slice;
pub mod slot;
#[cfg(verus_keep_ghost)]
pub mod spec;
pub mod strict;

pub use slice::{
    compact, compact_map, compact_map_st, dedup_by, map_in_place, map_in_place_st, swap,
};
pub use slot::{replace, update};

#[cfg(not(verus_keep_ghost))]
#[doc(hidden)]
pub use fip_strict::certs::{__fip_strict_replace, __fip_strict_swap};
