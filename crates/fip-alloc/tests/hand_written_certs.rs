//! Pins the hand-written strict certificates of this crate (none). Adding one requires
//! updating this list and justifying it.

#[test]
fn hand_written_certificates_are_exactly_the_documented_ones() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let found: Vec<(String, String)> = fip_testkit::certs::hand_written(&dir)
        .into_iter()
        .map(|(f, _, line)| {
            let file = f
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            let ident = line
                .split(|c: char| !(c.is_alphanumeric() || c == '_'))
                .find(|w| w.starts_with("__fip_strict_"))
                .unwrap_or("")
                .to_string();
            (file, ident)
        })
        .collect();
    // None since phase 5 (decision 2026-11-06-redesign-verus-allocates): the
    // certificates are generated by `#[fip_macros::fip(strict ..)]`/`(total)`.
    assert_eq!(found, Vec::<(String, String)>::new());
}

/// The generated certificate names its function and records `total`'s
/// `panic_macros = false`.
#[test]
fn generated_certificate_carries_its_name() {
    assert_eq!(fip_alloc::__fip_strict_refill.allocs_for("refill"), 0);
    assert!(fip_alloc::__fip_strict_refill.no_panic_macros_for("refill"));
}
